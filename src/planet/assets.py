"""The site stylesheet, published under a content hash.

Static files are cached for a day, so the stylesheet's URL changes whenever
its content does. It is the hand-written `static/css/style.css` plus the
syntax highlighting rules generated by `planet.highlight`.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path

from planet.highlight import stylesheet as code_stylesheet

SOURCE = Path("css/style.css")  # relative to the static directory


@dataclass(frozen=True)
class Stylesheet:
    path: str  # relative to the site root
    content: str

    @property
    def href(self) -> str:
        return f"/{self.path}"


def stylesheet(static_dir: Path | None) -> Stylesheet:
    source = static_dir / SOURCE if static_dir else None
    hand_written = source.read_text(encoding="utf-8") if source and source.exists() else ""
    content = f"{hand_written}\n{code_stylesheet()}"
    digest = hashlib.sha256(content.encode()).hexdigest()[:12]
    return Stylesheet(f"static/css/style.{digest}.css", content)
